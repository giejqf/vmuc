//! `vmuc start`, `stop` and `shell`, and the per-instance `ssh.config`.

use std::fs::{self, File};
use std::os::unix::process::CommandExt;
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use anyhow::{Context, bail};
use vmuc_config::VmucHome;
use vmuc_config::paths::instance as files;
use vmuc_proto::{ControlRequest, ControlResponse, EventKind};

use crate::instance::Instance;
use crate::state;
use crate::{control, keys};

/// How long `stop` waits for the guest to power off.
const STOP_WAIT: Duration = Duration::from_secs(90);
/// How long `stop --force` waits before killing the VMM outright.
const FORCE_GRACE: Duration = Duration::from_secs(10);

/// The ssh host alias in `ssh.config`.
pub fn ssh_host(name: &str) -> String {
    format!("vmuc-{name}")
}

/// `~/.vmuc/NAME/ssh.config`: ssh through the agent tunnel over vsock,
/// with a persistent master connection so repeated shells are instant.
pub fn write_ssh_config(
    home: &VmucHome,
    inst: &Instance,
    user: &str,
    forward_agent: bool,
) -> anyhow::Result<()> {
    let exe = std::env::current_exe()?;
    let text = format!(
        "# Generated by vmuc; `ssh -F {cfg} {host}`.\n\
         Host {host}\n\
         \x20 User {user}\n\
         \x20 IdentityFile \"{key}\"\n\
         \x20 IdentitiesOnly yes\n\
         \x20 PreferredAuthentications publickey\n\
         \x20 StrictHostKeyChecking no\n\
         \x20 UserKnownHostsFile /dev/null\n\
         \x20 LogLevel ERROR\n\
         \x20 ForwardAgent {fwd}\n\
         \x20 ControlMaster auto\n\
         \x20 ControlPath \"{dir}/ssh.sock\"\n\
         \x20 ControlPersist 5m\n\
         \x20 ProxyCommand \"{exe}\" _proxy {name} 22\n",
        cfg = inst.dir.join(files::SSH_CONFIG).display(),
        host = ssh_host(&inst.name),
        key = home.ssh_key().display(),
        fwd = if forward_agent { "yes" } else { "no" },
        dir = inst.dir.display(),
        exe = exe.display(),
        name = inst.name,
    );
    fs::write(inst.dir.join(files::SSH_CONFIG), text)?;
    Ok(())
}

pub fn start(home: &VmucHome, name: &str, timeout: Duration) -> anyhow::Result<()> {
    let (inst, mut child, started) = spawn_vmm(home, name, false)?;
    let verb = if crate::suspend::exists(&inst.dir) {
        "resuming"
    } else {
        "starting"
    };
    eprintln!(
        "{verb} {name} (log: {})",
        inst.dir.join(files::VMM_LOG).display()
    );
    wait_ready(&inst, &mut child, started, timeout)
}

/// `start --foreground`: the VMM stays attached to this terminal (its log
/// goes there) until the guest powers off; Ctrl-C reaches it as well and
/// powers the guest off, and this process reports how it ended.
pub fn start_foreground(home: &VmucHome, name: &str, timeout: Duration) -> anyhow::Result<()> {
    let (inst, mut child, started) = spawn_vmm(home, name, true)?;
    // Ctrl-C is for the VMM (same process group); stay to report.
    // SAFETY: ignoring SIGINT in this process only; the child already runs.
    unsafe { libc::signal(libc::SIGINT, libc::SIG_IGN) };
    eprintln!("starting {name} in the foreground; Ctrl-C powers it off");
    wait_ready(&inst, &mut child, started, timeout)?;
    let status = child.wait()?;
    if status.success() {
        eprintln!("{name} stopped");
        Ok(())
    } else {
        bail!("the VMM exited with {status}")
    }
}

fn spawn_vmm(
    home: &VmucHome,
    name: &str,
    foreground: bool,
) -> anyhow::Result<(Instance, std::process::Child, Instant)> {
    let inst = Instance::open(home, name)?;
    if let Some(pid) = state::running_pid(&inst.dir) {
        bail!("{name} is already running (pid {pid})");
    }
    let resolved = inst.resolved(home)?;
    keys::ensure_keypair(home)?;
    write_ssh_config(home, &inst, &resolved.user.name, resolved.ssh.forward_agent)?;
    let _ = fs::remove_file(inst.dir.join(files::EVENTS));

    let mut cmd = Command::new(std::env::current_exe()?);
    cmd.args(["_vmm", name])
        .current_dir(&inst.dir)
        .stdin(Stdio::null());
    if !foreground {
        let log = File::create(inst.dir.join(files::VMM_LOG))?;
        cmd.stdout(log.try_clone()?).stderr(log);
        // SAFETY: setsid is async-signal-safe; it detaches the VMM from our
        // session so closing the terminal does not take the VM down.
        unsafe {
            cmd.pre_exec(|| {
                if libc::setsid() < 0 {
                    return Err(std::io::Error::last_os_error());
                }
                Ok(())
            });
        }
    }
    let started = Instant::now();
    let child = cmd.spawn().context("spawning the VMM")?;
    Ok((inst, child, started))
}

/// Follows the VMM's events until the guest is ready.
fn wait_ready(
    inst: &Instance,
    child: &mut std::process::Child,
    started: Instant,
    timeout: Duration,
) -> anyhow::Result<()> {
    let name = &inst.name;
    let mut shown = 0;
    loop {
        let events = state::read_events(&inst.dir);
        for e in events.iter().skip(shown) {
            match &e.kind {
                EventKind::Requirement {
                    step,
                    total,
                    description,
                    done: false,
                    failed: false,
                } => {
                    eprintln!("  [{step}/{total}] waiting for {description}");
                }
                EventKind::Resumed { restore_ms, .. } => {
                    eprintln!("  resumed from its suspended state in {restore_ms} ms");
                }
                EventKind::Running { .. } => {
                    eprintln!(
                        "{name} is running ({:.1} s); `vmuc shell {name}`",
                        started.elapsed().as_secs_f64()
                    );
                    return Ok(());
                }
                EventKind::Warning { message } => eprintln!("  warning: {message}"),
                EventKind::Degraded { errors } => {
                    bail!("{name} is degraded: {}", errors.join("; "))
                }
                EventKind::Exiting { reason } => {
                    bail!("{name} stopped while starting: {reason}{}", log_tail(inst))
                }
                _ => {}
            }
        }
        shown = events.len();
        if let Some(status) = child.try_wait()? {
            bail!("the VMM exited ({status}) while starting{}", log_tail(inst));
        }
        if started.elapsed() > timeout {
            bail!(
                "{name} did not become ready within {timeout:?}; it keeps booting (see {})",
                inst.dir.join(files::VMM_LOG).display()
            );
        }
        std::thread::sleep(Duration::from_millis(20));
    }
}

fn log_tail(inst: &Instance) -> String {
    let text = fs::read_to_string(inst.dir.join(files::VMM_LOG)).unwrap_or_default();
    let lines: Vec<&str> = text.lines().rev().take(8).collect();
    if lines.is_empty() {
        String::new()
    } else {
        format!(
            "\nlast lines of vmm.log:\n  {}",
            lines.into_iter().rev().collect::<Vec<_>>().join("\n  ")
        )
    }
}

pub fn stop(home: &VmucHome, name: &str, force: bool) -> anyhow::Result<()> {
    let inst = Instance::open(home, name)?;
    let Some(pid) = state::running_pid(&inst.dir) else {
        state::remove_pid(&inst.dir);
        eprintln!("{name} is not running");
        return Ok(());
    };
    match control::request(&inst.dir, &ControlRequest::Stop { force })? {
        ControlResponse::Ok => {}
        other => bail!("stop: {other:?}"),
    }
    let limit = if force { FORCE_GRACE } else { STOP_WAIT };
    let started = Instant::now();
    while state::pid_alive(pid) {
        if started.elapsed() > limit {
            if !force {
                bail!("{name} (pid {pid}) is still running; try `vmuc stop --force {name}`");
            }
            // The VMM acknowledged the forced stop but cannot finish
            // tearing the VM down (a device thread stuck in the host).
            // The kernel reclaims a killed process's VM and memory.
            eprintln!("{name}: the VMM did not exit; killing pid {pid}");
            state::kill(pid)?;
            state::remove_pid(&inst.dir);
            break;
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    eprintln!("stopped {name} ({:.1} s)", started.elapsed().as_secs_f64());
    Ok(())
}

/// Replaces this process with `ssh` into the instance, starting in
/// `workdir` (a guest path) or, by default, wherever the current host
/// directory appears in the guest through a share.
pub fn shell(
    home: &VmucHome,
    name: &str,
    workdir: Option<&str>,
    command: &[String],
) -> anyhow::Result<()> {
    let inst = Instance::open(home, name)?;
    if state::running_pid(&inst.dir).is_none() {
        bail!("{name} is not running; `vmuc start {name}` first");
    }
    let mapped = match workdir {
        Some(_) => None,
        None => std::env::current_dir()
            .ok()
            .and_then(|cwd| guest_path(&inst.resolved(home).ok()?.mounts, &cwd)),
    };
    let mut cmd = Command::new("ssh");
    cmd.arg("-F").arg(inst.dir.join(files::SSH_CONFIG));
    let remote = remote_command(workdir, mapped.as_deref(), command);
    if remote.is_some() && atty_stdin() {
        cmd.arg("-t");
    }
    cmd.arg(ssh_host(name));
    if let Some(remote) = remote {
        cmd.arg("--").arg(remote);
    }
    Err(anyhow::anyhow!("exec ssh: {}", cmd.exec()))
}

/// The remote command line, if any: `cd` into the directory first (an
/// explicit one must exist; the mapped default is best effort), then the
/// command or a login shell.
fn remote_command(
    workdir: Option<&str>,
    mapped: Option<&str>,
    command: &[String],
) -> Option<String> {
    let cd = match (workdir, mapped) {
        (Some(d), _) => Some(format!("cd {} && ", shell_quote(d))),
        (None, Some(d)) => Some(format!("cd {} 2>/dev/null; ", shell_quote(d))),
        (None, None) => None,
    };
    match (cd, command.is_empty()) {
        (None, true) => None,
        (None, false) => Some(command.join(" ")),
        (Some(cd), true) => Some(format!("{cd}exec \"$SHELL\" -l")),
        (Some(cd), false) => Some(format!("{cd}{}", command.join(" "))),
    }
}

/// Where host directory `dir` is in the guest, through the share with the
/// longest matching location.
fn guest_path(
    mounts: &[vmuc_config::defaults::ResolvedMount],
    dir: &std::path::Path,
) -> Option<String> {
    mounts
        .iter()
        .filter_map(|m| {
            let rest = dir.strip_prefix(&m.location).ok()?;
            let depth = m.location.components().count();
            Some((depth, std::path::Path::new(&m.mount_point).join(rest)))
        })
        .max_by_key(|(depth, _)| *depth)
        .map(|(_, p)| p.display().to_string())
}

fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

fn atty_stdin() -> bool {
    // SAFETY: isatty only inspects the descriptor.
    unsafe { libc::isatty(0) == 1 }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_current_directory_maps_through_the_deepest_share() {
        use std::path::Path;
        let m = |location: &str, mount_point: &str| vmuc_config::defaults::ResolvedMount {
            location: location.into(),
            mount_point: mount_point.into(),
            writable: false,
            dax: false,
        };
        let mounts = [m("/Users/me", "/Users/me"), m("/Users/me/src", "/src")];
        assert_eq!(
            guest_path(&mounts, Path::new("/Users/me/docs")).as_deref(),
            Some("/Users/me/docs")
        );
        assert_eq!(
            guest_path(&mounts, Path::new("/Users/me/src/vmuc")).as_deref(),
            Some("/src/vmuc")
        );
        assert_eq!(guest_path(&mounts, Path::new("/opt")), None);
    }

    #[test]
    fn remote_commands_cd_first() {
        let cmd = |c: &[&str]| c.iter().map(|s| (*s).to_owned()).collect::<Vec<_>>();
        assert_eq!(remote_command(None, None, &[]), None);
        assert_eq!(
            remote_command(None, None, &cmd(&["uname", "-a"])).as_deref(),
            Some("uname -a")
        );
        assert_eq!(
            remote_command(Some("/w d"), None, &[]).as_deref(),
            Some("cd '/w d' && exec \"$SHELL\" -l")
        );
        assert_eq!(
            remote_command(None, Some("/src/it's"), &cmd(&["make"])).as_deref(),
            Some("cd '/src/it'\\''s' 2>/dev/null; make")
        );
    }

    #[test]
    fn ssh_config_points_at_our_proxy_and_key() {
        let dir = tempfile::tempdir().unwrap();
        let home = VmucHome::new(dir.path());
        let inst_dir = dir.path().join("dev");
        fs::create_dir_all(&inst_dir).unwrap();
        let inst = Instance {
            name: "dev".into(),
            dir: inst_dir.clone(),
        };
        write_ssh_config(&home, &inst, "alice", false).unwrap();
        let text = fs::read_to_string(inst_dir.join(files::SSH_CONFIG)).unwrap();
        assert!(text.contains("Host vmuc-dev\n"));
        assert!(text.contains("  User alice\n"));
        assert!(text.contains("_proxy dev 22"));
        assert!(text.contains(&format!("IdentityFile \"{}\"", home.ssh_key().display())));
        assert!(text.contains("ForwardAgent no"));
    }
}
