//! `vmuc start`, `stop` and `shell`, and the per-instance `ssh.config`.

use std::fs::{self, File};
use std::os::unix::process::CommandExt;
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use anyhow::{Context, bail};
use vmuc_config::VmucHome;
use vmuc_config::paths::instance as files;
use vmuc_proto::{ControlRequest, ControlResponse, EventKind};

use crate::instance::Instance;
use crate::state;
use crate::{control, keys};

/// The ssh host alias in `ssh.config`.
pub fn ssh_host(name: &str) -> String {
    format!("vmuc-{name}")
}

/// `~/.vmuc/NAME/ssh.config`: ssh through the agent tunnel over vsock,
/// with a persistent master connection so repeated shells are instant.
pub fn write_ssh_config(
    home: &VmucHome,
    inst: &Instance,
    user: &str,
    forward_agent: bool,
) -> anyhow::Result<()> {
    let exe = std::env::current_exe()?;
    let text = format!(
        "# Generated by vmuc; `ssh -F {cfg} {host}`.\n\
         Host {host}\n\
         \x20 User {user}\n\
         \x20 IdentityFile \"{key}\"\n\
         \x20 IdentitiesOnly yes\n\
         \x20 PreferredAuthentications publickey\n\
         \x20 StrictHostKeyChecking no\n\
         \x20 UserKnownHostsFile /dev/null\n\
         \x20 LogLevel ERROR\n\
         \x20 ForwardAgent {fwd}\n\
         \x20 ControlMaster auto\n\
         \x20 ControlPath \"{dir}/ssh.sock\"\n\
         \x20 ControlPersist 5m\n\
         \x20 ProxyCommand \"{exe}\" _proxy {name} 22\n",
        cfg = inst.dir.join(files::SSH_CONFIG).display(),
        host = ssh_host(&inst.name),
        key = home.ssh_key().display(),
        fwd = if forward_agent { "yes" } else { "no" },
        dir = inst.dir.display(),
        exe = exe.display(),
        name = inst.name,
    );
    fs::write(inst.dir.join(files::SSH_CONFIG), text)?;
    Ok(())
}

pub fn start(home: &VmucHome, name: &str, timeout: Duration) -> anyhow::Result<()> {
    let inst = Instance::open(home, name)?;
    if let Some(pid) = state::running_pid(&inst.dir) {
        bail!("{name} is already running (pid {pid})");
    }
    let resolved = inst.resolved(home)?;
    keys::ensure_keypair(home)?;
    write_ssh_config(home, &inst, &resolved.user.name, resolved.ssh.forward_agent)?;
    let _ = fs::remove_file(inst.dir.join(files::EVENTS));

    let log = File::create(inst.dir.join(files::VMM_LOG))?;
    let mut cmd = Command::new(std::env::current_exe()?);
    cmd.args(["_vmm", name])
        .current_dir(&inst.dir)
        .stdin(Stdio::null())
        .stdout(log.try_clone()?)
        .stderr(log);
    // SAFETY: setsid is async-signal-safe; it detaches the VMM from our
    // session so closing the terminal does not take the VM down.
    unsafe {
        cmd.pre_exec(|| {
            if libc::setsid() < 0 {
                return Err(std::io::Error::last_os_error());
            }
            Ok(())
        });
    }
    let started = Instant::now();
    let mut child = cmd.spawn().context("spawning the VMM")?;
    eprintln!(
        "starting {name} (log: {})",
        inst.dir.join(files::VMM_LOG).display()
    );

    let mut shown = 0;
    loop {
        let events = state::read_events(&inst.dir);
        for e in events.iter().skip(shown) {
            match &e.kind {
                EventKind::Requirement {
                    step,
                    total,
                    description,
                    done: false,
                    failed: false,
                } => {
                    eprintln!("  [{step}/{total}] waiting for {description}");
                }
                EventKind::Running { .. } => {
                    eprintln!(
                        "{name} is running ({:.1} s); `vmuc shell {name}`",
                        started.elapsed().as_secs_f64()
                    );
                    return Ok(());
                }
                EventKind::Warning { message } => eprintln!("  warning: {message}"),
                EventKind::Degraded { errors } => {
                    bail!("{name} is degraded: {}", errors.join("; "))
                }
                EventKind::Exiting { reason } => {
                    bail!("{name} stopped while starting: {reason}{}", log_tail(&inst))
                }
                _ => {}
            }
        }
        shown = events.len();
        if let Some(status) = child.try_wait()? {
            bail!(
                "the VMM exited ({status}) while starting{}",
                log_tail(&inst)
            );
        }
        if started.elapsed() > timeout {
            bail!(
                "{name} did not become ready within {timeout:?}; it keeps booting (see {})",
                inst.dir.join(files::VMM_LOG).display()
            );
        }
        std::thread::sleep(Duration::from_millis(20));
    }
}

fn log_tail(inst: &Instance) -> String {
    let text = fs::read_to_string(inst.dir.join(files::VMM_LOG)).unwrap_or_default();
    let lines: Vec<&str> = text.lines().rev().take(8).collect();
    if lines.is_empty() {
        String::new()
    } else {
        format!(
            "\nlast lines of vmm.log:\n  {}",
            lines.into_iter().rev().collect::<Vec<_>>().join("\n  ")
        )
    }
}

pub fn stop(home: &VmucHome, name: &str, force: bool) -> anyhow::Result<()> {
    let inst = Instance::open(home, name)?;
    let Some(pid) = state::running_pid(&inst.dir) else {
        state::remove_pid(&inst.dir);
        eprintln!("{name} is not running");
        return Ok(());
    };
    match control::request(&inst.dir, &ControlRequest::Stop { force })? {
        ControlResponse::Ok => {}
        other => bail!("stop: {other:?}"),
    }
    let started = Instant::now();
    while state::pid_alive(pid) {
        if started.elapsed() > Duration::from_secs(90) {
            bail!("{name} (pid {pid}) is still running; try `vmuc stop --force {name}`");
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    eprintln!("stopped {name} ({:.1} s)", started.elapsed().as_secs_f64());
    Ok(())
}

/// Replaces this process with `ssh` into the instance.
pub fn shell(home: &VmucHome, name: &str, command: &[String]) -> anyhow::Result<()> {
    let inst = Instance::open(home, name)?;
    if state::running_pid(&inst.dir).is_none() {
        bail!("{name} is not running; `vmuc start {name}` first");
    }
    let mut cmd = Command::new("ssh");
    cmd.arg("-F").arg(inst.dir.join(files::SSH_CONFIG));
    if !command.is_empty() && atty_stdin() {
        cmd.arg("-t");
    }
    cmd.arg(ssh_host(name));
    if !command.is_empty() {
        cmd.arg("--").args(command);
    }
    Err(anyhow::anyhow!("exec ssh: {}", cmd.exec()))
}

fn atty_stdin() -> bool {
    // SAFETY: isatty only inspects the descriptor.
    unsafe { libc::isatty(0) == 1 }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ssh_config_points_at_our_proxy_and_key() {
        let dir = tempfile::tempdir().unwrap();
        let home = VmucHome::new(dir.path());
        let inst_dir = dir.path().join("dev");
        fs::create_dir_all(&inst_dir).unwrap();
        let inst = Instance {
            name: "dev".into(),
            dir: inst_dir.clone(),
        };
        write_ssh_config(&home, &inst, "alice", false).unwrap();
        let text = fs::read_to_string(inst_dir.join(files::SSH_CONFIG)).unwrap();
        assert!(text.contains("Host vmuc-dev\n"));
        assert!(text.contains("  User alice\n"));
        assert!(text.contains("_proxy dev 22"));
        assert!(text.contains(&format!("IdentityFile \"{}\"", home.ssh_key().display())));
        assert!(text.contains("ForwardAgent no"));
    }
}
